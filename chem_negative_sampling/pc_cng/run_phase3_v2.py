def _write_records_csv(path: Path, recs: List[Dict]) -> None:
    if not recs:
        return
    with open(path, "w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=[
            "reaction_smiles", "negative_smiles", "label", "score",
            "experimental_group", "reaction_family", "yield_bin",
            "method", "is_positive",
        ])
        writer.writeheader()
        for r in recs:
            writer.writerow({k: r.get(k, "") for k in r})


def _print_table(table: List[Dict]) -> None:
    """Pretty-print the horizontal comparison table."""
    if not table:
        return
    methods = set()
    for row in table:
        methods.update(row.keys())
    methods.discard("scenario")
    methods = sorted(methods)
    # Header
    print(f"  {'scenario':<20} " + " ".join(f"{m:<22}" for m in methods))
    for row in table:
        vals = []
        for m in methods:
            v = row.get(m)
            vals.append(f"{v:.4f}" if isinstance(v, (int, float)) else "  -  ")
        print(f"  {row['scenario']:<20} " + " ".join(f"{v:<22}" for v in vals))


