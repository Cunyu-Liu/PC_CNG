def build_budget_matched_datasets(
    train_rows,
    test_rows,
    generators: Dict[str, Any],
    fp_fn=reaction_fp_enhanced,
) -> Dict[str, Tuple[Optional[np.ndarray], np.ndarray, List[Dict], List[Dict]]]:
    """Build datasets for ALL arms with STRICT budget matching.

    Returns ``{method: (X_train, y_train, train_records, test_records)}``.

    Budget matching:
      1. For each method, generate negatives for the SAME set of positives.
      2. Keep only positives whose negative was successfully generated by
         EVERY method (intersection).
      3. All methods end up with identical n_pos and n_neg.

    This eliminates the "more samples = better" confound (spec section G3
    problem two).
    """
    # Step 1: for each method, generate (positive_rxn, neg_rxn) pairs.
    method_pairs_train: Dict[str, List[Tuple[str, str, dict]]] = {}
    method_pairs_test: Dict[str, List[Tuple[str, str, dict]]] = {}

    for method, gen in generators.items():
        train_pairs = _generate_pairs(train_rows, gen, fp_fn)
        test_pairs = _generate_pairs(test_rows, gen, fp_fn)
        method_pairs_train[method] = train_pairs
        method_pairs_test[method] = test_pairs

    # Step 2: intersect valid positive indices across methods (train).
    # Use the positive reaction_smiles as the key.
    train_keys_per_method = [
        {p[0] for p in pairs} for pairs in method_pairs_train.values()
    ]
    common_train_keys = set.intersection(*train_keys_per_method) if train_keys_per_method else set()
    test_keys_per_method = [
        {p[0] for p in pairs} for pairs in method_pairs_test.values()
    ]
    common_test_keys = set.intersection(*test_keys_per_method) if test_keys_per_method else set()

    print(f"  [budget] train: {len(common_train_keys)} common positives "
          f"(min arm: {min(len(p) for p in method_pairs_train.values()) if method_pairs_train else 0})")
    print(f"  [budget] test:  {len(common_test_keys)} common positives "
          f"(min arm: {min(len(p) for p in method_pairs_test.values()) if method_pairs_test else 0})")

    # Step 3: build (X, y, records) per method using only common positives.
    result: Dict[str, Tuple[Optional[np.ndarray], np.ndarray, List[Dict], List[Dict]]] = {}
    for method, gen in generators.items():
        X_tr, y_tr, rec_tr = _pairs_to_dataset(
            [p for p in method_pairs_train[method] if p[0] in common_train_keys],
            method, fp_fn, split="train")
        X_te, y_te, rec_te = _pairs_to_dataset(
            [p for p in method_pairs_test[method] if p[0] in common_test_keys],
            method, fp_fn, split="test")
        if X_tr is None or len(X_tr) < 10:
            result[method] = (None, np.array([]), [], [])
            continue
        result[method] = (X_tr, y_tr, rec_tr, rec_te)
    return result


def _generate_pairs(rows, generator, fp_fn) -> List[Tuple[str, str, dict]]:
    """For each row, generate (pos_rxn, neg_rxn, row_meta)."""
    pairs: List[Tuple[str, str, dict]] = []
    for _, row in rows.iterrows():
        rxn = row.get("reaction_smiles")
        if not rxn or not isinstance(rxn, str):
            continue
        pos_fp = fp_fn(rxn)
        if pos_fp is None:
            continue
        neg_rxn = generator.generate(rxn)
        if neg_rxn is None:
            continue
        meta = {
            "experimental_group": str(row.get("experimental_group",
                                              row.get("split_key", "default"))),
            "reaction_family": str(row.get("reaction_family", "unknown")),
            "yield_bin": int(row.get("yield_bin", 0)) if "yield_bin" in row else 0,
        }
        pairs.append((rxn, neg_rxn, meta))
    return pairs


def _pairs_to_dataset(pairs: List[Tuple[str, str, dict]], method: str,
                      fp_fn, split: str) -> Tuple[Optional[np.ndarray], np.ndarray, List[Dict]]:
    """Convert (pos_rxn, neg_rxn, meta) pairs into (X, y, records)."""
    fps: List[np.ndarray] = []
    labels: List[int] = []
    records: List[Dict] = []
    for pos_rxn, neg_rxn, meta in pairs:
        pos_fp = fp_fn(pos_rxn)
        neg_fp = fp_fn(neg_rxn)
        if pos_fp is None or neg_fp is None:
            continue
        fps.append(pos_fp)
        labels.append(1)
        records.append({
            "reaction_smiles": pos_rxn, "negative_smiles": pos_rxn,
            "label": 1, "score": 0.0, "method": method,
            "is_positive": True, **meta,
        })
        fps.append(neg_fp)
        labels.append(0)
        records.append({
            "reaction_smiles": neg_rxn, "negative_smiles": neg_rxn,
            "label": 0, "score": 0.0, "method": method,
            "is_positive": False, **meta,
        })
    if not fps:
        return None, np.array([]), []
    X = np.vstack(fps)
    y = np.array(labels, dtype=np.float32)
    return X, y, records


