def run_split_v2(split_name: str, split_data: Dict, methods: Sequence[str],
                 model, device, seed: int, n_bootstrap: int,
                 use_gnn: bool = False) -> Dict:
    """Run all methods + negative controls on one split."""
    print(f"\n[phase3v2] === Split: {split_name} ===")
    print(f"  train={len(split_data['train'])}  test={len(split_data['test'])}")

    results: Dict[str, Dict] = {}
    test_records_by_method: Dict[str, List[Dict]] = {}

    # Build generators for each method (with robust fallback)
    generators: Dict[str, Any] = {}

    # Build real product pool for proper random_mismatch baseline
    # (sample real products from training set instead of 7 trivial molecules)
    product_pool = []
    try:
        for _, row in split_data["train"].iterrows():
            rxn = row.get("reaction_smiles", "")
            if rxn and isinstance(rxn, str) and ">" in rxn:
                parts = rxn.split(">")
                if len(parts) == 3 and parts[2]:
                    product_pool.append(parts[2])
    except Exception:
        pass
    if product_pool:
        print(f"  [random] using real product pool: {len(product_pool)} products")

    for method in methods:
        try:
            if method == METHOD_LEARNED and model is None:
                results[method] = {"error": "model_not_available", "skipped": True}
                continue
            if method == METHOD_LEARNED:
                base = NegativeGenerator(method, model=model, device=device, seed=seed)
            elif method == METHOD_RANDOM and product_pool:
                # Pass real product pool for meaningful random_mismatch baseline
                base = NegativeGenerator(method, seed=seed, product_pool=product_pool)
            else:
                base = NegativeGenerator(method, seed=seed)
            # Wrap with robust fallback (Improvement A)
            generators[method] = RobustNegativeGenerator(base, seed=seed, verbose=False)
        except Exception as exc:
            results[method] = {"error": str(exc)}
            print(f"  [{method}] generator build ERROR: {exc}")

    # Budget-matched datasets across all real methods (Improvement C)
    if generators:
        print(f"  [budget] building budget-matched datasets for {list(generators.keys())} ...")
        try:
            budget = build_budget_matched_datasets(
                split_data["train"], split_data["test"], generators)
        except Exception as exc:
            print(f"  [budget] ERROR: {exc}")
            budget = {}

        # Train + evaluate each method on its budget-matched slice
        for method, gen in generators.items():
            if method not in budget:
                continue
            X_tr, y_tr, rec_tr, rec_te = budget[method]
            if X_tr is None or len(X_tr) < 10:
                results[method] = {"error": "insufficient budget-matched data",
                                   "n_train": 0}
                print(f"  [{method}] insufficient budget-matched data")
                continue
            t0 = time.time()
            print(f"  [{method}] training ({len(X_tr)} samples) ...")
            clf = make_classifier(X_tr.shape[1], seed, use_gnn=use_gnn)
            if use_gnn and hasattr(clf, "fit_reactions"):
                train_rxns = [r["reaction_smiles"] for r in rec_tr]
                test_rxns = [r["reaction_smiles"] for r in rec_te]
                clf.fit_reactions(train_rxns, y_tr, epochs=MLP_EPOCHS,
                                  batch_size=MLP_BATCH, lr=MLP_LR, verbose=False)
                scores = np.asarray(clf.predict_proba_reactions(test_rxns)).flatten()
                for i, rec in enumerate(rec_te):
                    if i < len(scores):
                        rec["score"] = float(scores[i])
            else:
                clf.train(X_tr, y_tr, epochs=MLP_EPOCHS, batch_size=MLP_BATCH,
                          lr=MLP_LR, verbose=False)
                # Predict on test
                X_te_fps = [reaction_fp_enhanced(r["reaction_smiles"]) for r in rec_te]
                valid = [i for i, f in enumerate(X_te_fps) if f is not None]
                if not valid:
                    results[method] = {"error": "all test fingerprints invalid"}
                    continue
                X_te = np.vstack([X_te_fps[i] for i in valid])
                scores = clf.predict_proba(X_te)
                for j, i in enumerate(valid):
                    rec_te[i]["score"] = float(scores[j])
                # Drop invalid records
                rec_te = [rec_te[i] for i in valid]

            auprc = auprc_metric(rec_te)
            macro = macro_auprc_metric(rec_te, bin_key="yield_bin")
            fam_macro = family_macro_auprc_metric(rec_te, family_key="reaction_family")
            elapsed = time.time() - t0
            results[method] = {
                "n_train": len(X_tr), "n_test": len(rec_te),
                "auprc": float(auprc), "macro_auprc": float(macro),
                "family_macro_auprc": float(fam_macro),
                "elapsed_sec": float(elapsed),
                "budget_matched": True,
            }
            test_records_by_method[method] = rec_te
            print(f"    AUPRC={auprc:.4f}  macro={macro:.4f}  "
                  f"fam_macro={fam_macro:.4f}  ({elapsed:.1f}s)")

    # Negative control arms (Improvement C)
    # Use rule_pc_cng generator for controls (always available)
    if METHOD_RULE in generators:
        base_rule = generators[METHOD_RULE]
        # randomized_label
        print(f"  [{METHOD_RAND_LABEL}] negative control ...")
        try:
            res = evaluate_method_v2(split_data["train"], split_data["test"],
                                     base_rule, seed, use_gnn=use_gnn,
                                     is_randomized_label=True)
            results[METHOD_RAND_LABEL] = {k: v for k, v in res.items()
                                          if k != "test_records"}
            if "test_records" in res:
                test_records_by_method[METHOD_RAND_LABEL] = res["test_records"]
                print(f"    AUPRC={res['auprc']:.4f}  (expect ~0.5)")
        except Exception as exc:
            results[METHOD_RAND_LABEL] = {"error": str(exc)}

        # shuffled_parent
        print(f"  [{METHOD_SHUFFLED_PARENT}] negative control ...")
        try:
            X_tr, y_tr, rec_tr = build_shuffled_parent_dataset(
                split_data["train"], base_rule)
            X_te, y_te, rec_te = build_shuffled_parent_dataset(
                split_data["test"], base_rule)
            if X_tr is not None and len(X_tr) >= 10 and X_te is not None:
                clf = make_classifier(X_tr.shape[1], seed, use_gnn=use_gnn)
                if use_gnn and hasattr(clf, "fit_reactions"):
                    train_rxns = [r["reaction_smiles"] for r in rec_tr]
                    test_rxns = [r["reaction_smiles"] for r in rec_te]
                    clf.fit_reactions(train_rxns, y_tr, epochs=MLP_EPOCHS,
                                      batch_size=MLP_BATCH, lr=MLP_LR, verbose=False)
                    scores = np.asarray(clf.predict_proba_reactions(test_rxns)).flatten()
                else:
                    clf.train(X_tr, y_tr, epochs=MLP_EPOCHS, batch_size=MLP_BATCH,
                              lr=MLP_LR, verbose=False)
                    scores = clf.predict_proba(X_te)
                for i, rec in enumerate(rec_te):
                    if i < len(scores):
                        rec["score"] = float(scores[i])
                results[METHOD_SHUFFLED_PARENT] = {
                    "n_train": len(X_tr), "n_test": len(rec_te),
                    "auprc": float(auprc_metric(rec_te)),
                    "macro_auprc": float(macro_auprc_metric(rec_te, bin_key="yield_bin")),
                    "family_macro_auprc": float(family_macro_auprc_metric(rec_te)),
                }
                test_records_by_method[METHOD_SHUFFLED_PARENT] = rec_te
                print(f"    AUPRC={results[METHOD_SHUFFLED_PARENT]['auprc']:.4f}")
            else:
                results[METHOD_SHUFFLED_PARENT] = {"error": "insufficient data"}
        except Exception as exc:
            results[METHOD_SHUFFLED_PARENT] = {"error": str(exc)}

    # Paired cluster bootstrap CI for real method pairs
    paired_ci: Dict = {}
    real_methods = [m for m in methods if m in test_records_by_method]
    pairs_to_compute = []
    for i, ch in enumerate(real_methods):
        for bl in real_methods[i + 1:]:
            pairs_to_compute.append((ch, bl))
    # Also compare each real method against negative controls
    for m in real_methods:
        for ctrl in (METHOD_RAND_LABEL, METHOD_SHUFFLED_PARENT):
            if ctrl in test_records_by_method:
                pairs_to_compute.append((m, ctrl))

    for challenger, baseline in pairs_to_compute:
        pair_key = f"{challenger}_vs_{baseline}"
        try:
            ch_recs = test_records_by_method[challenger]
            bl_recs = test_records_by_method[baseline]
            n = min(len(ch_recs), len(bl_recs))
            ch_recs = ch_recs[:n]
            bl_recs = bl_recs[:n]
            ci = paired_cluster_bootstrap(
                ch_recs, bl_recs, metric_fn=auprc_metric,
                cluster_key="experimental_group",
                n_bootstrap=n_bootstrap, seed=seed,
            )
            paired_ci[pair_key] = ci
            print(f"  [CI] {pair_key}: delta={ci['delta_mean']:.4f} "
                  f"CI=[{ci['delta_ci_low']:.4f}, {ci['delta_ci_high']:.4f}] "
                  f"p={ci['p_value']:.4f}")
        except Exception as exc:
            paired_ci[pair_key] = {"error": str(exc)}

    return {
        "split_name": split_name,
        "n_train": len(split_data["train"]),
        "n_test": len(split_data["test"]),
        "methods": {m: {k: v for k, v in r.items() if k != "test_records"}
                     for m, r in results.items()},
        "paired_ci": paired_ci,
        "test_records": test_records_by_method,
    }


# ---------------------------------------------------------------------------
# Improvement D: Holm correction across all scenarios
# ---------------------------------------------------------------------------

def apply_holm_across_scenarios(all_results: Dict[str, Dict],
                                alpha: float = 0.05) -> Dict:
    """Collect all paired CI p-values across scenarios, apply Holm correction.

    Returns ``{pair_key: {scenario: {adjusted_p, rejected, original_p, ...}}}``.
    """
    # Collect (scenario, pair_key, p_value, delta, ci)
    all_tests: List[Dict] = []
    for scenario, res in all_results.items():
        if "paired_ci" not in res:
            continue
        for pair_key, ci in res["paired_ci"].items():
            if "error" in ci:
                continue
            all_tests.append({
                "scenario": scenario,
                "pair_key": pair_key,
                "p_value": ci.get("p_value", 1.0),
                "delta_mean": ci.get("delta_mean", 0.0),
                "delta_ci_low": ci.get("delta_ci_low", 0.0),
                "delta_ci_high": ci.get("delta_ci_high", 0.0),
            })

    if not all_tests:
        return {}

    # Holm correction across ALL tests (family-wise)
    p_values = [t["p_value"] for t in all_tests]
    holm_results = holm_correction(p_values, alpha=alpha)

    # Map back
    holm_summary: Dict[str, Dict] = {}
    for test, holm in zip(all_tests, holm_results):
        scenario = test["scenario"]
        pair_key = test["pair_key"]
        holm_summary.setdefault(pair_key, {})[scenario] = {
            "original_p": test["p_value"],
            "adjusted_p": holm["adjusted_p"],
            "rejected": holm["rejected"],
            "delta_mean": test["delta_mean"],
            "delta_ci_low": test["delta_ci_low"],
            "delta_ci_high": test["delta_ci_high"],
            "ci_all_positive": test["delta_ci_low"] > 0,
        }
    return holm_summary


# ---------------------------------------------------------------------------
# Horizontal comparison table (user requirement)
# ---------------------------------------------------------------------------

def build_comparison_table(all_results: Dict[str, Dict]) -> List[Dict]:
    """Build a horizontal comparison table: scenario × method → AUPRC.

    User explicitly requires 横向对比表 between multiple models.
    """
    table: List[Dict] = []
    for scenario, res in all_results.items():
        if "methods" not in res:
            continue
        row = {"scenario": scenario}
        for method, mres in res["methods"].items():
            if "error" in mres and "auprc" not in mres:
                row[method] = None
            else:
                row[method] = mres.get("auprc", None)
        table.append(row)
    return table


