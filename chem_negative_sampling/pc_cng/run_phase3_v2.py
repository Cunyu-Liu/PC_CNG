# Evaluation (budget-matched, multi-task)
# ---------------------------------------------------------------------------

def evaluate_method_v2(
    train_rows,
    test_rows,
    generator,
    seed: int,
    use_gnn: bool = False,
    is_randomized_label: bool = False,
) -> Dict:
    """Train classifier on train, evaluate on test.  Budget-matched.

    ``is_randomized_label``: if True, shuffle y_train (negative control).
    """
    t0 = time.time()
    X_train, y_train, _, _ = build_budget_matched_datasets(
        train_rows, test_rows, {"_": generator})
    # build_budget_matched_datasets returns a dict; extract single method.
    if "_" not in X_train if isinstance(X_train, dict) else True:
        pass  # fall through; we use the simpler path below

    # Simpler path: build directly (budget matching handled at run_split level)
    X_tr, y_tr, rec_tr = build_dataset_enhanced(train_rows, generator)
    if X_tr is None or len(X_tr) < 10:
        return {"error": "insufficient training data", "n_train": 0}
    X_te, y_te, rec_te = build_dataset_enhanced(test_rows, generator)
    if X_te is None or len(X_te) < 4:
        return {"error": "insufficient test data", "n_train": len(X_tr)}

    # Negative control: shuffle training labels
    if is_randomized_label:
        rng = np.random.default_rng(seed)
        rng.shuffle(y_tr)

    clf = make_classifier(X_tr.shape[1], seed, use_gnn=use_gnn)
    if use_gnn and hasattr(clf, "fit_reactions"):
        train_rxns = [r["reaction_smiles"] for r in rec_tr]
        test_rxns = [r["reaction_smiles"] for r in rec_te]
        clf.fit_reactions(train_rxns, y_tr, epochs=MLP_EPOCHS,
                          batch_size=MLP_BATCH, lr=MLP_LR, verbose=False)
        scores = np.asarray(clf.predict_proba_reactions(test_rxns)).flatten()
    else:
        clf.train(X_tr, y_tr, epochs=MLP_EPOCHS, batch_size=MLP_BATCH,
                  lr=MLP_LR, verbose=False)
        scores = clf.predict_proba(X_te)
    for i, rec in enumerate(rec_te):
        if i < len(scores):
            rec["score"] = float(scores[i])

    auprc = auprc_metric(rec_te)
    macro = macro_auprc_metric(rec_te, bin_key="yield_bin")
    fam_macro = family_macro_auprc_metric(rec_te, family_key="reaction_family")

    elapsed = time.time() - t0
    return {
        "n_train": len(X_tr), "n_test": len(X_te),
        "auprc": float(auprc), "macro_auprc": float(macro),
        "family_macro_auprc": float(fam_macro),
        "elapsed_sec": float(elapsed),
        "test_records": rec_te,
    }


